_ANCHORS = sorted(EVENT_DISTANCES_M.items(), key=lambda kv: kv[1])


def factor(age: int, sex: str, event: str) -> float:
    """Exact WMA 2023 table lookup; age clamped to [30, 110]."""
    a = min(max(int(age), MIN_AGE), MAX_AGE)
    return AGE_FACTORS[sex.upper()][event][a - MIN_AGE]


def _interp_loglog(x: float, x0: float, x1: float, y0: float, y1: float) -> float:
    t = log(x / x0) / log(x1 / x0)
    return y0 * (y1 / y0) ** t


def grade(distance_m: float, time_s: float, age: int, sex: str) -> tuple[float, float] | None:
    """Age-graded performance, or None outside 3000m..marathon.

    Returns (graded_pct, graded_time_s): graded_pct is WR_open / graded_time
    (1.0 = open-class world record pace).
    """
    if distance_m < MIN_DISTANCE_M or distance_m > MAX_DISTANCE_M:
        return None
    sex_u = sex.upper()
    for i, (event, dist) in enumerate(_ANCHORS):
        if dist >= distance_m:
            if dist == distance_m or i == 0:
                wr = OPEN_WR_S[sex_u][event]
                f = factor(age, sex_u, event)
            else:
                lo_event, lo_dist = _ANCHORS[i - 1]
                wr = _interp_loglog(
                    distance_m,
                    lo_dist,
                    dist,
                    OPEN_WR_S[sex_u][lo_event],
                    OPEN_WR_S[sex_u][event],
                )
                f = _interp_loglog(
                    distance_m,
                    lo_dist,
                    dist,
                    factor(age, sex_u, lo_event),
                    factor(age, sex_u, event),
                )
            graded = time_s * f
            return (wr / graded, graded)
    return None


def daily_best_graded(activities: list[Activity], profile: RunnerProfile) -> pd.Series:
    """Daily best age-graded pct over eligible outdoor runs (>= 3km, running only).

    Index: activity date; values: best (max) graded pct that day, fraction.
    """
    best: dict[pd.Timestamp, float] = {}
    for a in activities:
        if a.sport != "running":
            continue
        age = a.date.year - profile.birth_year
        g = grade(a.distance_m, a.duration_s, age, profile.sex)
        if g is None:
            continue
        d = pd.Timestamp(a.date)
        if g[0] > best.get(d, 0.0):
            best[d] = g[0]
    if not best:
        return pd.Series(dtype=float)
    return pd.Series(best).sort_index()
